#!/usr/bin/env python3
"""Generate the Race Coach packages for Claude, Gemini and ChatGPT from one source.

Source of truth: coach/race-coach.md (platform-neutral workflow and coaching rules).

    python3 scripts/build_coach_packages.py            # (re)generate the committed files
    python3 scripts/build_coach_packages.py --check    # fail if they are out of date (CI)
    python3 scripts/build_coach_packages.py --zip DIR  # also build race-coach.zip for claude.ai

Formats (verified against the official docs on 2026-11-02, see docs/clients.md):
- Claude Code plugin: plugins/garmin-race-coach/{.claude-plugin/plugin.json,.mcp.json,
  skills/race-coach/SKILL.md}, listed by .claude-plugin/marketplace.json at the repo root.
- claude.ai / Claude Desktop: race-coach.zip with race-coach/SKILL.md (frontmatter limited to
  upload-safe keys: name, description, license).
- Gemini CLI extension: extensions/gemini/garmin-race-coach/{gemini-extension.json,GEMINI.md}.
- ChatGPT: instructions/chatgpt/system-prompt.md (to paste; connector setup in docs/clients.md).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "coach" / "race-coach.md"
PLUGIN = "garmin-race-coach"
SKILL = "race-coach"
COMMAND = "garmin-coach-mcp"
DESCRIPTION = (
    "Running race coach on Garmin data: sets a race goal, builds a safe phased training plan "
    "from the athlete's Garmin history, exports or sends workouts to Garmin, and adapts the plan "
    "with weekly check-ins. Use when the athlete talks about a race, a training plan, their "
    "Garmin runs, recovery, or a weekly check-in."
)
#: Environment passed to the server; empty values mean "not set" for the server.
SERVER_ENV = [
    ("GARMIN_PERSONAL_API_KEY", "Garmin Personal API key", True),
    ("GARMIN_PERSONAL_API_KEY_EXPIRES", "Personal API key expiry date (YYYY-MM-DD)", False),
    ("GARMIN_ALLOW_UNOFFICIAL_READS", "Allow unofficial reads (true/false)", False),
    ("GARMIN_ALLOW_UNOFFICIAL_WRITES", "Allow unofficial workout writes (true/false)", False),
    ("GARMIN_TOKEN_DIR", "Token directory of a previous `garmin-coach-mcp --login`", False),
    ("GARMIN_COACH_DATA_DIR", "Where goals, plans and exports are stored", False),
]
GENERATED = "<!-- Generated by scripts/build_coach_packages.py from coach/race-coach.md. "
GENERATED += "Do not edit by hand. -->"


def version() -> str:
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    raw = re.search(r'^version = "([^"]+)"', text, re.M)
    assert raw, "version not found in pyproject.toml"
    # PEP 440 "2.0.0.dev0" -> semver "2.0.0-dev0"
    return re.sub(r"\.(dev\d+)$", r"-\1", raw.group(1))


def body() -> str:
    return SOURCE.read_text(encoding="utf-8").strip() + "\n"


def skill_md(extra_frontmatter: bool = True) -> str:
    # json.dumps gives a double-quoted scalar: valid YAML even with ": " inside the text.
    front = [f"name: {SKILL}", f"description: {json.dumps(DESCRIPTION)}"]
    if extra_frontmatter:
        front.append("license: AGPL-3.0-only")
    return "---\n" + "\n".join(front) + "\n---\n\n" + GENERATED + "\n\n" + body()


def files() -> dict[Path, str]:
    v = version()
    plugin_dir = ROOT / "plugins" / PLUGIN
    mcp_env = {name: f"${{{name}:-}}" for name, _d, _s in SERVER_ENV}
    out: dict[Path, str] = {
        plugin_dir / ".claude-plugin" / "plugin.json": json.dumps(
            {
                "name": PLUGIN,
                "version": v,
                "description": "Race Coach: Garmin data, safe training plans and weekly "
                "adaptation (local MCP server + race-coach skill).",
                "author": {"name": "garmin-coach-mcp contributors"},
                "license": "AGPL-3.0-only",
                "repository": "https://github.com/mrosano1987/garmin-mcp-server-1",
                "keywords": ["garmin", "running", "training-plan", "mcp"],
            },
            indent=2,
        ),
        plugin_dir / ".mcp.json": json.dumps(
            {"mcpServers": {"garmin-coach": {"command": COMMAND, "args": [], "env": mcp_env}}},
            indent=2,
        ),
        plugin_dir / "skills" / SKILL / "SKILL.md": skill_md(),
        # Project skill for Claude Code sessions opened on this repository (cloud/mobile).
        ROOT / ".claude" / "skills" / SKILL / "SKILL.md": skill_md(),
        # Project-level server for Claude Code sessions opened on this repository (also the
        # cloud sessions usable from the Claude mobile app): runs from ./.venv, installed
        # on first use by scripts/setup-venv.sh.
        ROOT / ".mcp.json": json.dumps(
            {
                "mcpServers": {
                    "garmin-coach": {
                        "command": "bash",
                        "args": ["${CLAUDE_PROJECT_DIR:-.}/scripts/coach-mcp.sh"],
                        "env": mcp_env,
                    }
                }
            },
            indent=2,
        ),
        ROOT / ".claude-plugin" / "marketplace.json": json.dumps(
            {
                "name": "garmin-coach",
                "owner": {"name": "garmin-coach-mcp contributors"},
                "description": "Garmin Race Coach: MCP server and race-coach skill for running "
                "training plans on Garmin data.",
                "plugins": [
                    {
                        "name": PLUGIN,
                        "source": f"./plugins/{PLUGIN}",
                        "description": "Race Coach on Garmin data (MCP server + skill).",
                        "version": v,
                    }
                ],
            },
            indent=2,
        ),
    }
    gemini_dir = ROOT / "extensions" / "gemini" / PLUGIN
    out[gemini_dir / "gemini-extension.json"] = json.dumps(
        {
            "name": PLUGIN,
            "version": v,
            "description": "Race Coach on Garmin data: goals, safe training plans, weekly "
            "adaptation.",
            "mcpServers": {"garmin-coach": {"command": COMMAND, "args": []}},
            "contextFileName": "GEMINI.md",
            "settings": [
                {"name": desc, "description": desc, "envVar": name, "sensitive": sensitive}
                for name, desc, sensitive in SERVER_ENV
            ],
        },
        indent=2,
    )
    out[gemini_dir / "GEMINI.md"] = GENERATED + "\n\n" + body()
    out[ROOT / "instructions" / "chatgpt" / "system-prompt.md"] = (
        GENERATED
        + "\n\n"
        + body()
        + "\n_Paste this text into the instructions of the ChatGPT project or custom GPT that "
        "uses the Garmin Coach connector (see docs/clients.md)._\n"
    )
    return {path: text if text.endswith("\n") else text + "\n" for path, text in out.items()}


def build_zip(out_dir: Path) -> Path:
    """claude.ai skill upload: top-level folder = skill name; only upload-safe frontmatter."""
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f"{SKILL}.zip"
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"{SKILL}/SKILL.md", skill_md())
    return target


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Fail if files are out of date.")
    parser.add_argument("--zip", type=Path, metavar="DIR", help="Also build the claude.ai zip.")
    args = parser.parse_args()
    stale = []
    for path, text in files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date (run scripts/build_coach_packages.py):", *stale, sep="\n  ")
        return 1
    if args.zip:
        print(f"wrote {build_zip(args.zip)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
